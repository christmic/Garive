/// Closed portable keys admitted by native Computer Use v1.
public enum NativeKeyboardKey: String, CaseIterable, Equatable, Sendable {
    case enter
    case tab
    case escape
    case backspace
    case delete
    case arrowUp = "arrow_up"
    case arrowDown = "arrow_down"
    case arrowLeft = "arrow_left"
    case arrowRight = "arrow_right"
    case home
    case end
    case pageUp = "page_up"
    case pageDown = "page_down"
    case space
}
